-- Dumping structure for procedure cup2018.spGetGameStatistics
DELIMITER //
CREATE DEFINER=`root`@`localhost` PROCEDURE `spGetGameStatistics`()
BEGIN
SELECT QUERY_1.GAME_ID, MASTER.TEAM_A, MASTER.TEAM_B, 
SUM(QUERY_1.TEAM_A) AS VITORIA_A, 
FORMAT( (SUM(QUERY_1.TEAM_A) / ( SUM(QUERY_1.TEAM_A) + SUM(QUERY_1.TEAM_B) + SUM(QUERY_1.TEAM_C)))*100, 2) AS PERC_VITORIA_A,
SUM(QUERY_1.TEAM_B) AS VITORIA_B, 
FORMAT( (SUM(QUERY_1.TEAM_B) / ( SUM(QUERY_1.TEAM_A) + SUM(QUERY_1.TEAM_B) + SUM(QUERY_1.TEAM_C)))*100, 2) AS PERC_VITORIA_B,
SUM(QUERY_1.TEAM_C) AS EMPATE,
FORMAT( (SUM(QUERY_1.TEAM_C) / ( SUM(QUERY_1.TEAM_A) + SUM(QUERY_1.TEAM_B) + SUM(QUERY_1.TEAM_C)))*100, 2) AS PERC_EMPATE
FROM (
			SELECT GAME_ID, COUNT(1) AS TEAM_A, 0 AS TEAM_B, 0 AS TEAM_C FROM BETS
			WHERE SCORE_A > SCORE_B AND GAME_ID in (SELECT GAME_ID FROM MASTER WHERE DATE_FORMAT(MASTER.GAME_DATE, '%Y-%m-%d') = (SELECT DATE_FORMAT(SYSDATE(), '%Y-%m-%d') FROM DUAL))
			GROUP BY GAME_ID
			UNION ALL
			SELECT GAME_ID, 0 AS TEAM_A, COUNT(1) AS TEAM_B, 0 AS TEAM_C FROM BETS
			WHERE SCORE_A < SCORE_B AND GAME_ID in (SELECT GAME_ID FROM MASTER WHERE DATE_FORMAT(MASTER.GAME_DATE, '%Y-%m-%d') = (SELECT DATE_FORMAT(SYSDATE(), '%Y-%m-%d') FROM DUAL))
			GROUP BY GAME_ID
			UNION ALL
			SELECT GAME_ID, 0 AS TEAM_A, 0 AS TEAM_B, COUNT(1) AS TEAM_C FROM BETS
			WHERE SCORE_A = SCORE_B AND GAME_ID in (SELECT GAME_ID FROM MASTER WHERE DATE_FORMAT(MASTER.GAME_DATE, '%Y-%m-%d') = (SELECT DATE_FORMAT(SYSDATE(), '%Y-%m-%d') FROM DUAL))
			GROUP BY GAME_ID
		) AS QUERY_1, MASTER
WHERE QUERY_1.GAME_ID = MASTER.GAME_ID
GROUP BY GAME_ID, MASTER.TEAM_A, MASTER.TEAM_B;
END//
