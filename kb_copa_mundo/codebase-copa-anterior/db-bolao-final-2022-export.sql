-- Dumping structure for procedure cup2018.spSetRanking
DELIMITER //
CREATE DEFINER=`root`@`localhost` PROCEDURE `spSetRanking`()
BEGIN
	
	DECLARE vUserId, vRoundId, vRoundPts, vTotalPts, rowidcount, vLastRanking INT;
	
	DECLARE c_ranking_round CURSOR FOR 
	select ranking.userid, ranking.ROUND_ID, ranking.ROUND_PTS
	from ranking
	where ranking.round_id = (select max(round_id) from rounds where round_status = 1)
	order by ranking.ROUND_PTS desc, ranking.USERID;
	
	DECLARE c_ranking_general CURSOR FOR 
	select ranking.userid, sum(ranking.ROUND_PTS) as TOTAL_PTS
	from ranking
	where ranking.round_id <= (select max(round_id) from rounds where round_status = 1)
	group by ranking.userid
	order by TOTAL_PTS desc, ranking.USERID;
	
	/* UPDATING ACCUMULATED POINTS */
	OPEN c_ranking_round;
	SET rowidcount = 1;
	SET @pos = 0;
	SET @previousRoundPts = -1;
	
	REPEAT
		FETCH FROM c_ranking_round into vUserId, vRoundId, vRoundPts;
		
		UPDATE ranking set accum_pts =  (select last_points from last_ranking where userid = vUserId) + vRoundPts
		where userid=vUserId and round_id = vRoundId;
		
		SET rowidcount = rowidcount + 1;
		
	UNTIL rowidcount > 45 END REPEAT;
	CLOSE c_ranking_round;

	/* UPDATING RANKING */
	OPEN c_ranking_general;
	SET rowidcount = 1;
	SET @pos = 0;
	SET @previousPts = -1;
	
	REPEAT
		FETCH FROM c_ranking_general into vUserId, vTotalPts;
		
		IF @previousPts != vTotalPts THEN
				
			SET @previousPts = vTotalPts;
			SET @pos = @pos + 1;
			
		END IF;
		
		UPDATE ranking set ranking.ranking=@pos, last_ranking= (select last_pos from last_ranking where userid = vUserId)
		where userid=vUserId and round_id = vRoundId;
		
		UPDATE last_ranking set last_pos = @pos, last_points = vTotalPts where userid = vUserId;
		
		SET rowidcount = rowidcount + 1;
		
	UNTIL rowidcount > 45 END REPEAT;
	CLOSE c_ranking_general;

END//
